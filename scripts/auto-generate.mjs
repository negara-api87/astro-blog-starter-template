function randomTopic() {
  // AI auto cari variasi topik biar tidak duplikat
  const t = baseTopics[Math.floor(Math.random()*baseTopics.length)];
  const year = new Date().getFullYear();
  const states = ["Texas","Florida","California","Ohio","New York","Arizona"];
  const state = states[Math.floor(Math.random()*states.length)];
  return `${t} in ${state} ${year}`;
}

